 result:=public.driver_documents('exempt',jsonb_build_object('driver_id',other_driver,'enabled',false));
 assert not (result->>'ready')::boolean,'Revoking exemption restores requirement';
 perform set_config('request.jwt.claim.sub',other_driver::text,true);
 assert not private.document_access(path),'Another driver cannot read document';
 assert not private.document_access(path,true),'Another driver cannot upload to owner folder';
 result:=public.driver_documents('list',jsonb_build_object('driver_id',driver));
 assert jsonb_array_length(result->'documents')=0,'Driver cannot list someone else by changing payload';
 perform set_config('request.jwt.claim.sub',passenger::text,true);
 assert not private.document_access(path),'Passenger cannot read document';
 rejected:=false;
 begin perform public.driver_documents('list','{}');exception when others then rejected:=true;end;
 assert rejected,'Passenger cannot use driver API';
 assert not (select public from storage.buckets where id='driver-documents'),'Bucket is private';
 assert not has_table_privilege('authenticated','private.driver_documents','UPDATE'),'No direct approval bypass';
 perform set_config('request.jwt.claim.sub',driver::text,true);
 perform set_config('test.document_path',path,true);
 execute 'set local role authenticated';
 assert (select count(*)=1 from storage.objects where bucket_id='driver-documents' and name=current_setting('test.document_path')),'Owner RLS allows reading';
 perform set_config('request.jwt.claim.sub',other_driver::text,true);
 assert (select count(*)=0 from storage.objects where bucket_id='driver-documents' and name=current_setting('test.document_path')),'Storage RLS denies other drivers';
 execute 'reset role';
 perform set_config('request.jwt.claim.sub',driver::text,true);
 rejected:=false;
 begin perform public.prepare_document_deletion('NO');exception when others then rejected:=true;end;
 assert rejected,'Document deletion requires account deletion confirmation';
 result:=public.prepare_document_deletion('ELIMINAR');
 assert jsonb_array_length(result)=6,'Account cleanup includes replaced and current files';
 assert not exists(select 1 from private.driver_documents where driver_id=driver),'Cleanup unlinks document records';
 assert private.document_unused(path),'Unlinked files can be removed through Storage';
end $test$;
