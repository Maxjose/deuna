 kind text;path text;old_path text;result jsonb;rejected boolean;
begin
 insert into auth.users(id) values(admin_id),(driver),(other_driver),(passenger);
 update public.profiles set role='admin' where id=admin_id;
 update public.profiles set role='driver',approved=true where id in(driver,other_driver);
 assert not private.documents_ready(driver),'Existing drivers require documents immediately';
 perform set_config('request.jwt.claim.sub',driver::text,true);
 rejected:=false;
 begin perform public.operate('available','{"available":true}');exception when others then rejected:=sqlerrm='Documentos pendientes';end;
 assert rejected,'Connection guarded before plan and VIP';
 rejected:=false;
 begin perform public.operate('accept',jsonb_build_object('id',gen_random_uuid()));exception when others then rejected:=sqlerrm='Documentos pendientes';end;
 assert rejected,'Acceptance guarded on server';
 rejected:=false;
 begin perform public.driver_documents('exempt',jsonb_build_object('enabled',true));exception when others then rejected:=true;end;
 assert rejected,'Driver cannot exempt himself';
 rejected:=false;
 begin perform public.driver_documents('review','{"approve":true}');exception when others then rejected:=true;end;
 assert rejected,'Driver cannot approve himself';
 foreach kind in array array['circulation','liability','quarters','license','medical'] loop
  path:=driver::text||'/'||kind||'/'||gen_random_uuid()::text||'.pdf';
  insert into storage.objects(bucket_id,name,metadata) values('driver-documents',path,'{"size":100,"mimetype":"application/pdf"}');
  result:=public.driver_documents('submit',jsonb_build_object('kind',kind,'path',path));
  assert not (result->>'ready')::boolean,'Uploading is not approval';
  perform set_config('request.jwt.claim.sub',admin_id::text,true);
  result:=public.driver_documents('review',jsonb_build_object('driver_id',driver,'kind',kind,'path',path,'approve',true));
  perform set_config('request.jwt.claim.sub',driver::text,true);
 end loop;
 assert private.documents_ready(driver),'All five approved';
 old_path:=path;
 path:=driver::text||'/medical/'||gen_random_uuid()::text||'.pdf';
 insert into storage.objects(bucket_id,name,metadata) values('driver-documents',path,'{"size":100,"mimetype":"application/pdf"}');
 result:=public.driver_documents('submit',jsonb_build_object('kind','medical','path',path));
 assert not private.documents_ready(driver),'Replacing an approved file resets approval';
 perform set_config('request.jwt.claim.sub',admin_id::text,true);
 rejected:=false;
 begin perform public.driver_documents('review',jsonb_build_object('driver_id',driver,'kind','medical','path',old_path,'approve',true));exception when others then rejected:=sqlerrm='Documento actualizado';end;
 assert rejected,'Stale review cannot approve replacement';
 rejected:=false;
 begin perform public.driver_documents('review',jsonb_build_object('driver_id',driver,'kind','medical','path',path,'approve',false));exception when others then rejected:=sqlerrm='Motivo requerido';end;
 assert rejected,'Rejecting requires reason';
 result:=public.driver_documents('review',jsonb_build_object('driver_id',driver,'kind','medical','path',path,'approve',false,'reason','No se lee'));
 assert exists(select 1 from private.driver_documents where driver_id=driver and reason='No se lee'),'Rejection reason stored';
 result:=public.driver_documents('exempt',jsonb_build_object('driver_id',other_driver,'enabled',true));
 assert (result->>'ready')::boolean and (result->>'exempt')::boolean,'Explicit exemption works with no documents';
