begin;
do $test$
#variable_conflict use_variable
declare a uuid:=gen_random_uuid();b uuid:=gen_random_uuid();u uuid:=gen_random_uuid();other_user uuid:=gen_random_uuid();id uuid;mid uuid:=gen_random_uuid();r jsonb;denied boolean;
begin
 insert into auth.users(id) values(a),(b),(u),(other_user);
 update public.profiles set role='admin' where profiles.id in(a,b);
 update public.profiles set role='driver' where profiles.id=u;
 perform set_config('request.jwt.claim.sub',u::text,true);
 r:=public.support('request','{"subject":"No puedo conectarme"}');id:=(r->>'id')::uuid;
 assert (public.support('request','{"subject":"Otra solicitud"}')->>'id')::uuid=id,'One open conversation per account';
 r:=public.support('fetch',jsonb_build_object('id',id));
 assert r->'thread'->>'status'='waiting','Request begins waiting';
 assert not (r?'profile'),'User cannot see admin profile panel';
 denied:=false;begin perform public.support('send',jsonb_build_object('id',id,'message_id',mid,'body','Hola'));exception when others then denied:=sqlerrm='Espera atencion';end;
 assert denied,'Cannot chat before manual claim';
 denied:=false;begin perform public.support('claim',jsonb_build_object('id',id));exception when others then denied:=true;end;
 assert denied,'User cannot claim';
 perform set_config('request.jwt.claim.sub',other_user::text,true);
 denied:=false;begin perform public.support('fetch',jsonb_build_object('id',id));exception when others then denied:=true;end;
 assert denied,'Other users cannot read';
 assert jsonb_array_length(public.support('list')->'items')=0,'User list is private';
 perform set_config('request.jwt.claim.sub',a::text,true);
 assert jsonb_array_length(public.support('list','{"status":"waiting"}')->'items')>=1,'Admin sees waiting queue';
 r:=public.support('claim',jsonb_build_object('id',id));
 assert r->'thread'->>'status'='active','Claim starts conversation';
 assert r->'profile'->>'role'='driver' and r->'profile'?'plan','Support sees basic driver information';
 perform set_config('request.jwt.claim.sub',b::text,true);
 denied:=false;begin perform public.support('claim',jsonb_build_object('id',id));exception when others then denied:=true;end;
 assert denied,'Second agent cannot take claimed conversation';
 denied:=false;begin perform public.support('send',jsonb_build_object('id',id,'message_id',gen_random_uuid(),'body','Hola'));exception when others then denied:=true;end;
 assert denied,'Only assigned agent can reply';
 perform set_config('request.jwt.claim.sub',u::text,true);
 r:=public.support('send',jsonb_build_object('id',id,'message_id',mid,'body','Hola soporte'));
 r:=public.support('send',jsonb_build_object('id',id,'message_id',mid,'body','Hola soporte'));
 assert jsonb_array_length(r->'messages')=1,'Retry does not duplicate message';
 perform set_config('request.jwt.claim.sub',a::text,true);
 r:=public.support('list','{"status":"active"}');
 assert exists(select 1 from jsonb_array_elements(r->'items')x where x->>'id'=id::text and (x->>'unread')::int=1),'Inbox unread marker';
 r:=public.support('fetch',jsonb_build_object('id',id));
 assert jsonb_array_length(r->'messages')=1,'Agent receives message';
 r:=public.support('list','{"status":"active"}');
 assert exists(select 1 from jsonb_array_elements(r->'items')x where x->>'id'=id::text and (x->>'unread')::int=0),'Fetch marks read';
 r:=public.support('send',jsonb_build_object('id',id,'message_id',gen_random_uuid(),'body','Te ayudamos'));
 assert jsonb_array_length(r->'messages')=2,'Assigned agent sends';
 r:=public.support('release',jsonb_build_object('id',id));
 assert r->'thread'->>'status'='waiting','Agent can return to queue';
 perform set_config('request.jwt.claim.sub',b::text,true);
 perform public.support('claim',jsonb_build_object('id',id));
 r:=public.support('resolve',jsonb_build_object('id',id));
 assert r->'thread'->>'status'='resolved','Agent resolves';
 perform set_config('request.jwt.claim.sub',u::text,true);
 denied:=false;begin perform public.support('send',jsonb_build_object('id',id,'message_id',gen_random_uuid(),'body','Otro mensaje'));exception when others then denied:=true;end;
 assert denied,'Resolved chat is read only';
 r:=public.support('request','{"subject":"Otra consulta diferente"}');
 assert r->>'id'<>id::text,'New request after resolution';
 perform public.delete_my_account('ELIMINAR');
 assert not exists(select 1 from private.support_threads where user_id=u),'Account deletion removes support history';
 assert not exists(select 1 from private.support_messages where thread_id=id),'Account cleanup cascades messages';
 assert not has_table_privilege('authenticated','private.support_messages','SELECT'),'Messages not exposed directly';
 assert not has_function_privilege('anon','public.support(text,jsonb)','EXECUTE'),'Anonymous API disabled';
end $test$;
rollback;
