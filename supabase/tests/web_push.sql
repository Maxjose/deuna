-- No real messages: all queue/pg_net changes roll back before network delivery.
begin;
do $test$
declare admin_id uuid:=gen_random_uuid(); a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); driver uuid:=gen_random_uuid();
 campaign uuid:=gen_random_uuid(); trip uuid:=gen_random_uuid(); endpoint_a text; endpoint_b text; endpoint_d text;
 token text; result jsonb; job jsonb; rejected boolean;
begin
 select worker_key into token from private.push_config where id=1;
 update private.push_config set enabled=false where id=1;
 insert into auth.users(id) values(admin_id),(a),(b),(driver);
 update public.profiles set role='admin' where id=admin_id;
 update public.profiles set role='driver',approved=true,available=true where id=driver;
 endpoint_a:='https://fcm.googleapis.com/fcm/send/test-'||a;
 endpoint_b:='https://fcm.googleapis.com/fcm/send/test-'||b;
 endpoint_d:='https://fcm.googleapis.com/fcm/send/test-'||driver;
 perform set_config('request.jwt.claim.sub',a::text,true);
 perform public.push_manage('subscribe',jsonb_build_object('endpoint',endpoint_a,'keys',jsonb_build_object('p256dh',repeat('A',87),'auth',repeat('A',22))));
 assert not (public.push_manage('info',jsonb_build_object('endpoint',endpoint_a))->>'promotions')::boolean,'Promotions must be opt-in';
 rejected:=false;
 begin perform public.push_manage('subscribe',jsonb_build_object('endpoint','https://127.0.0.1/private','keys',jsonb_build_object('p256dh',repeat('A',87),'auth',repeat('A',22))));exception when check_violation then rejected:=true;end;
 assert rejected,'Must reject SSRF endpoint';
 rejected:=false;
 begin perform public.push_manage('preview','{"audience":"all"}');exception when others then rejected:=true;end;
 assert rejected,'Passenger cannot manage campaigns';
 perform public.push_manage('preferences',jsonb_build_object('endpoint',endpoint_a,'promotions',true));
 perform set_config('request.jwt.claim.sub',b::text,true);
 assert not (public.push_manage('info',jsonb_build_object('endpoint',endpoint_a))->>'enabled')::boolean,'Another user cannot read subscription';
 perform public.push_manage('unsubscribe',jsonb_build_object('endpoint',endpoint_a));
 assert exists(select 1 from private.push_devices where endpoint=endpoint_a),'Another user cannot remove subscription';
 perform public.push_manage('subscribe',jsonb_build_object('endpoint',endpoint_b,'keys',jsonb_build_object('p256dh',repeat('B',87),'auth',repeat('B',22))));
 perform set_config('request.jwt.claim.sub',driver::text,true);
 perform public.push_manage('subscribe',jsonb_build_object('endpoint',endpoint_d,'keys',jsonb_build_object('p256dh',repeat('C',87),'auth',repeat('C',22))));
 perform set_config('request.jwt.claim.sub',admin_id::text,true);
 result:=public.push_manage('campaign',jsonb_build_object('id',campaign,'title','Prueba','body','Solo suscritos','audience','passenger'));
 assert exists(select 1 from private.push_jobs where campaign_id=campaign and recipient_id=a),'Opt-in recipient queued';
 assert not exists(select 1 from private.push_jobs where campaign_id=campaign and recipient_id=b),'Opt-out recipient excluded';
 perform public.push_manage('campaign',jsonb_build_object('id',campaign,'title','Prueba','body','Solo suscritos','audience','passenger'));
 assert (select count(*)=1 from private.push_jobs where campaign_id=campaign and recipient_id=a),'Retry does not duplicate campaign';
 perform set_config('request.jwt.claim.sub',a::text,true);
 perform public.push_manage('preferences',jsonb_build_object('endpoint',endpoint_a,'promotions',false));
 perform public.push_manage('test',jsonb_build_object('endpoint',endpoint_a));
 update private.push_config set enabled=true where id=1;
 result:=public.push_worker(token,'claim','{}');
 assert (select status='skipped' from private.push_jobs where campaign_id=campaign and recipient_id=a),'Revoked consent skips queued advertising';
 select value into job from jsonb_array_elements(result) where value->>'endpoint'=endpoint_a;
 assert job is not null,'Device test claimed';
 perform public.push_worker(token,'finish',jsonb_build_object('id',job->>'id','lease',job->>'lease','code',503));
 assert (select status='pending' and available_at>now() from private.push_jobs where id=(job->>'id')::uuid),'Transient error retries with backoff';
 update private.push_jobs set available_at=now() where id=(job->>'id')::uuid;
 result:=public.push_worker(token,'claim','{}');
 select value into job from jsonb_array_elements(result) where value->>'endpoint'=endpoint_a;
 perform public.push_worker(token,'finish',jsonb_build_object('id',job->>'id','lease',gen_random_uuid(),'code',201));
 assert (select status='processing' from private.push_jobs where id=(job->>'id')::uuid),'Wrong lease cannot acknowledge';
 perform public.push_worker(token,'finish',jsonb_build_object('id',job->>'id','lease',job->>'lease','code',201));
 assert (select status='sent' from private.push_jobs where id=(job->>'id')::uuid),'Success recorded';
 update private.push_config set enabled=false where id=1;
 perform set_config('request.jwt.claim.sub',b::text,true);
 insert into public.trips(id,passenger_id,origin,destination) values(trip,b,'Test origin','Test destination');
 assert exists(select 1 from private.push_jobs where trip_id=trip and recipient_id=driver and trip_status='searching'),'Available approved driver notified';
 update public.trips set status='assigned',driver_id=driver where id=trip;
 assert exists(select 1 from private.push_jobs where trip_id=trip and recipient_id=b and trip_status='assigned'),'Passenger notified of acceptance';
 update private.push_config set enabled=true where id=1;
 result:=public.push_worker(token,'claim','{}');
 assert (select status='skipped' from private.push_jobs where trip_id=trip and recipient_id=driver and trip_status='searching'),'Obsolete trip notifications skipped';
 select value into job from jsonb_array_elements(result) where value->>'endpoint'=endpoint_b;
 perform public.push_worker(token,'finish',jsonb_build_object('id',job->>'id','lease',job->>'lease','code',410));
 assert not exists(select 1 from private.push_devices where endpoint=endpoint_b),'Expired subscription removed';
 rejected:=false;begin perform public.push_worker('bad','claim','{}');exception when others then rejected:=true;end;
 assert rejected,'Worker requires secret';
 assert not has_table_privilege('authenticated','private.push_devices','SELECT'),'Browser cannot read device table';
 assert not has_table_privilege('anon','private.push_config','SELECT'),'Anonymous cannot read worker key';
end;$test$;
rollback;
