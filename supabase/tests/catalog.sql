-- All fixtures are transactional; no demo places remain in the real catalog.
begin;
do $test$
declare admin_id uuid:=gen_random_uuid();passenger uuid:=gen_random_uuid();tag text:=replace(gen_random_uuid()::text,'-','');
 batch uuid:=gen_random_uuid();payload jsonb;result jsonb;search jsonb;saved_id uuid;rejected boolean;row jsonb;many jsonb;
begin
 insert into auth.users(id) values(admin_id),(passenger);
 update public.profiles set role='admin' where id=admin_id;
 perform set_config('request.jwt.claim.sub',admin_id::text,true);
 row:=jsonb_build_object('source','qa_catalog','external_id',tag,'name','Farmacia Águila '||tag,'latitude',11.087,'longitude',-71.603,'aliases',jsonb_build_array('Don José '||tag),'address','Calle de prueba','municipality','Mara');
 payload:=jsonb_build_object('version',1,'batch_id',batch,'places',jsonb_build_array(row));
 result:=public.catalog_admin('import',payload);
 assert (result->>'inserted')::integer=1,'Insert count';
 select id into saved_id from private.catalog_places where source='qa_catalog' and external_id=tag;
 assert public.catalog_admin('import',payload)=result,'Repeated batch returns original result';
 assert (select count(*)=1 from private.catalog_places where source='qa_catalog' and external_id=tag),'No duplicates';
 rejected:=false;begin perform public.catalog_admin('import',payload||jsonb_build_object('places',jsonb_build_array(row||'{"name":"Cambio"}')));exception when others then rejected:=true;end;
 assert rejected,'Batch id cannot be reused for other data';
 perform set_config('request.jwt.claim.sub',passenger::text,true);
 search:=public.catalog_search('don jose '||tag,11.087,-71.603);
 assert exists(select 1 from jsonb_array_elements(search) p where (p->>'id')::uuid=saved_id),'Aliases and accents searchable';
 search:=public.catalog_search('farmacia agila '||tag,11.087,-71.603);
 assert exists(select 1 from jsonb_array_elements(search) p where (p->>'id')::uuid=saved_id),'Fuzzy name searchable';
 assert jsonb_array_length(public.catalog_search('%%_',11.087,-71.603))=0,'Wildcard-only input is not a full catalog dump';
 rejected:=false;begin perform public.catalog_admin('list','{}');exception when others then rejected:=true;end;
 assert rejected,'Passengers cannot administer catalog';
 rejected:=false;begin perform public.catalog_admin('import',payload);exception when others then rejected:=true;end;
 assert rejected,'Passengers cannot import';
 perform set_config('request.jwt.claim.sub',admin_id::text,true);
 perform public.catalog_admin('toggle',jsonb_build_object('id',saved_id,'active',false));
 row:=row||jsonb_build_object('name','Farmacia Corregida '||tag,'latitude',11.09);
 result:=public.catalog_admin('import',jsonb_build_object('version',1,'batch_id',gen_random_uuid(),'places',jsonb_build_array(row)));
 assert (result->>'updated')::integer=1,'Update count';
 assert (select id=saved_id and not active and latitude=11.09 from private.catalog_places where source='qa_catalog' and external_id=tag),'Stable id and inactive status preserved';
 assert not exists(select 1 from jsonb_array_elements(public.catalog_search('don jose '||tag,11.09,-71.603)) p where (p->>'id')::uuid=saved_id),'Inactive places hidden';
 rejected:=false;
 begin perform public.catalog_admin('import',jsonb_build_object('version',1,'batch_id',gen_random_uuid(),'places',jsonb_build_array(row||jsonb_build_object('external_id',tag||'-atomic'),row||jsonb_build_object('external_id',tag||'-bad','latitude',100))));exception when others then rejected:=true;end;
 assert rejected,'Invalid row rejects entire batch';
 assert not exists(select 1 from private.catalog_places where external_id=tag||'-atomic'),'Earlier row rolled back';
 select jsonb_agg(row||jsonb_build_object('external_id',tag||'-'||n)) into many from generate_series(1,101)n;
 rejected:=false;begin perform public.catalog_admin('import',jsonb_build_object('version',1,'batch_id',gen_random_uuid(),'places',many));exception when others then rejected:=true;end;
 assert rejected,'Batch capped at 100';
 assert not has_table_privilege('authenticated','private.catalog_places','SELECT'),'No raw table access';
 assert not has_function_privilege('anon','public.catalog_search(text,double precision,double precision)','EXECUTE'),'Anonymous search denied';
 assert not has_function_privilege('anon','public.catalog_admin(text,jsonb)','EXECUTE'),'Anonymous management denied';
 perform set_config('request.jwt.claim.sub','',true);
 rejected:=false;begin perform public.catalog_search('farmacia',null,null);exception when others then rejected:=true;end;
 assert rejected,'Search requires session';
end;$test$;
rollback;
